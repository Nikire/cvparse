/**
 * Generates the public evaluation dataset:
 *
 *   npm run eval:dataset        (tsx eval/generate/index.ts)
 *
 * Writes eval/dataset/files/<id>.<ext>, eval/dataset/truth/<id>.json, eval/dataset/manifest.json,
 * eval/dataset/VERSION and eval/dataset/README.md. Everything is seeded: running it twice on the
 * same machine produces byte-identical files.
 */

